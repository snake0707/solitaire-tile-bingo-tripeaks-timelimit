MAX_SOLVER_ROUNDS = 3       # 每种策略最多跑几轮
GREEDY_PHASE_RATIO = 0.6    # 前N%步数纯贪心（无回溯），之后启用决策树回溯
MAX_CONSECUTIVE_FLIPS = 9   # 连续翻手牌上限，超过则判定 layout 无效
