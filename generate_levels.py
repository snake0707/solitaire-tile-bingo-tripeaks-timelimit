# ── Image mapping config (loaded from config/image_mapping.json) ──────────────
# Generated by exporting from config/all_image_cards.xlsx.
# Contains:
#   prefixMap: C-class categoryName→prefix mapping (where name.lower() ≠ prefix)
#   imageMap:  fixed (categoryName, word) → image_filename for all A/C class cards

IMAGE_MAPPING_CONFIG = None  # loaded lazily

def _load_image_mapping():
    global IMAGE_MAPPING_CONFIG
    if IMAGE_MAPPING_CONFIG is not None:
        return
    config_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'config', 'image_mapping.json')
    if os.path.exists(config_path):
        with open(config_path, 'r', encoding='utf-8') as f:
            IMAGE_MAPPING_CONFIG = json.load(f)
        print("Loaded image mapping: %d prefix maps, %d image maps" % (
            len(IMAGE_MAPPING_CONFIG.get('prefixMap', {})),
            len(IMAGE_MAPPING_CONFIG.get('imageMap', {})),
        ))
    else:
        IMAGE_MAPPING_CONFIG = {'prefixMap': {}, 'imageMap': {}}
        print("Warning: config/image_mapping.json not found, using fallback")

def get_image_prefix(category_name):
    """Get image prefix for a category. Handles C-class name→prefix mapping."""
    _load_image_mapping()
    lower = category_name.lower()
    return IMAGE_MAPPING_CONFIG.get('prefixMap', {}).get(lower, lower)

# Match mode: 'random' means don't try name matching (images ≠ card words)
IMAGE_RANDOM_PREFIXES = {
    'baking', 'toys', 'xmas', 'deck',
}


# ── Read v2 Excel ───────────────────────────────────────────────────────────

def read_level_sheet(filepath):
    """Read the 'level' sheet → dict[int, LevelConfig]."""
    wb = openpyxl.load_workbook(filepath, read_only=True, data_only=True)
    ws = wb['level']
    rows = list(ws.iter_rows(values_only=True))
    wb.close()

    if len(rows) < 2:
        return {}

    # Row 0 = headers: level, 收集槽数量, 桌面牌1-5数量, 类别数量, 牌数量, 基础步数, 真实步数调整比例, 求解范围, 真实步数, 求解步数下限, 求解步数上限, delta
    result = {}
    for row in rows[1:]:
        level = row[0]
        if level is None:
            continue
        level = int(level)
        max_slots = int(row[1])
        # Column sizes: columns 2-6 (桌面牌1数量 to 桌面牌5数量), skip None
        column_sizes = []
        for i in range(2, 7):
            if i < len(row) and row[i] is not None:
                column_sizes.append(int(row[i]))
        num_categories = int(row[7]) if len(row) > 7 and row[7] is not None else 0
        base_steps = int(row[9]) if len(row) > 9 and row[9] is not None else 0
        adjust_ratio = float(row[10]) if len(row) > 10 and row[10] is not None else 0
        solve_range = float(row[11]) if len(row) > 11 and row[11] is not None else 0
        # Compute derived fields (replicate Excel formulas for v3 compatibility)
        # 真实步数 = ROUND(基础步数 * (1 + 调整比例/100), 0)
        display_steps = int(row[12]) if len(row) > 12 and row[12] is not None else round(base_steps * (1 + adjust_ratio / 100))
        # delta = ROUND(基础步数 * 求解范围/100/2, 0)
        delta = round(base_steps * solve_range / 100 / 2)
        # 求解步数下限 = 基础步数 - delta, 求解步数上限 = 基础步数 + delta
        solve_step_min = int(row[13]) if len(row) > 13 and row[13] is not None else base_steps - delta
        solve_step_max = int(row[14]) if len(row) > 14 and row[14] is not None else base_steps + delta

        result[level] = {
            'maxSlots': max_slots,
            'columnSizes': column_sizes,
            'numCategories': num_categories,
            'maxSteps': base_steps,
            'displaySteps': display_steps,
            'solveStepMin': solve_step_min,
            'solveStepMax': solve_step_max,
        }
    return result


def read_card_sheet(filepath):
    """Read the 'card' sheet → dict[int, list[CategoryDef]]."""
    wb = openpyxl.load_workbook(filepath, read_only=True, data_only=True)
    ws = wb['card']
    rows = list(ws.iter_rows(values_only=True))
    wb.close()

    if len(rows) < 2:
        return {}

    # Row 0 = headers: level, category, categoryId, categoryName, 图片, 单词数量, 1-8
    result = {}
    for row in rows[1:]:
        level = row[0]
        if level is None:
            continue
        level = int(level)

        cat_name = str(row[3]).strip() if row[3] else ''
        is_image = row[4] == 1 or row[4] == '1'
        card_count = int(row[5]) if row[5] else 0

        # Card words: columns 6-13 (indices 1-8)
        card_words = []
        for i in range(6, 14):
            if i < len(row) and row[i] is not None:
                w = str(row[i]).strip()
                if w and w != '':
                    card_words.append(w)

        cat_def = {
            'categoryId': str(row[2]).strip() if row[2] else '',
            'categoryName': cat_name,
            'isImage': is_image,
            'cardCount': card_count,
            'cardWords': card_words,
        }

        if level not in result:
            result[level] = []
        result[level].append(cat_def)

    return result


# ── Image index ─────────────────────────────────────────────────────────────

def build_image_index(res_dir):
    """Scan res/Item/*.png, build { prefix: { item_name: filename } } index."""
    item_dir = os.path.join(res_dir, 'Item')
    if not os.path.isdir(item_dir):
        print("Warning: %s not found" % item_dir)
        return {}

    index = {}  # prefix -> { normalized_name: full_filename_without_ext }
    all_prefixes = set()

    for fname in sorted(os.listdir(item_dir)):
        if not fname.endswith('.png'):
            continue
        base = fname[:-4]  # remove .png
        parts = base.split('_')
        if len(parts) < 3:
            continue
        prefix = parts[0]
        # item name = middle parts (between prefix and trailing number)
        item_name = '_'.join(parts[1:-1])  # e.g. 'diamondring', 'doubledeckerbus'
        all_prefixes.add(prefix)

        if prefix not in index:
            index[prefix] = {}
        index[prefix][item_name.lower()] = fname[:-4]  # store without .png

    return index, all_prefixes


def resolve_image(category_name, card_word, image_index, used_images, rng):
    """Resolve a card word to an image path for an image-type category.

    Priority: 1) fixed mapping from config/image_mapping.json
              2) name matching (word → image itemname)
              3) random unused image from prefix (fallback for unmapped categories)
    Returns: "res/Item/<filename>.png" or None if no mapping available.
    """
    # 1. Check fixed mapping first
    _load_image_mapping()
    fixed_key = '%s/%s' % (category_name, card_word)
    fixed_img = IMAGE_MAPPING_CONFIG.get('imageMap', {}).get(fixed_key)
    if fixed_img:
        return "res/Item/%s" % fixed_img if not fixed_img.startswith('res/') else fixed_img

    # 2. Fallback: original logic (for unmapped / new categories)
    idx, all_prefixes = image_index

    prefix = get_image_prefix(category_name)

    if prefix not in idx:
        print("  Warning: prefix '%s' not found in image index (category '%s')" % (prefix, category_name))
        return None

    prefix_items = idx[prefix]

    # Track used images per prefix
    if prefix not in used_images:
        used_images[prefix] = set()

    matched_key = None

    # If not a random-only prefix, try name matching first
    if prefix not in IMAGE_RANDOM_PREFIXES:
        normalized = card_word.lower().replace(' ', '')
        if normalized in prefix_items:
            matched_key = normalized

    # Fallback to random unused image
    if matched_key is None:
        available = [k for k in prefix_items if k not in used_images[prefix]]
        if available:
            matched_key = rng.choice(available)
        elif prefix_items:
            # All used, pick any
            matched_key = rng.choice(list(prefix_items.keys()))

    if matched_key is None:
        return None

    used_images[prefix].add(matched_key)
    return "res/Item/%s.png" % prefix_items[matched_key]


# ── Card generation ─────────────────────────────────────────────────────────

def generate_cards_for_level(level_config, categories, image_index, rng):
    """Generate all cards for a level and distribute to tableau + hand pile.

    Returns: { tableau, categoryTargets, handPile }
    """
    column_sizes = level_config['columnSizes']
    max_slots = level_config['maxSlots']
    tableau_size = sum(column_sizes)

    # Generate all cards
    all_cards = []
    category_targets = {}
    used_images = {}

    for cat_def in categories:
        cat_name = cat_def['categoryName']
        is_image = cat_def['isImage']
        card_words = cat_def['cardWords']

        # Category key: image categories use name, text categories use name_word
        cat_key = cat_name if is_image else cat_name + '_word'

        # Gold card
        gold_card = {
            'type': 'gold',
            'category': cat_key,
            'name': cat_name,
            'isText': not is_image,
        }
        all_cards.append(gold_card)

        # Regular cards
        category_targets[cat_key] = len(card_words)
        for word in card_words:
            card = {
                'type': 'regular',
                'category': cat_key,
                'name': word,
                'isText': not is_image,
            }
            if is_image:
                img_path = resolve_image(cat_name, word, image_index, used_images, rng)
                if img_path:
                    card['image'] = img_path
            all_cards.append(card)

    total_cards = len(all_cards)
    hand_count = total_cards - tableau_size

    if hand_count < 0:
        print("  Warning: total cards (%d) < tableau size (%d), padding needed" % (total_cards, tableau_size))
        hand_count = 0

    # Shuffle all cards (10 rounds for better randomization)
    for _ in range(10):
        rng.shuffle(all_cards)

    # Split into tableau cards and hand pile
    tableau_cards = all_cards[:tableau_size]
    hand_pile = all_cards[tableau_size:]

    # Build tableau columns
    tableau = []
    offset = 0
    for col_size in column_sizes:
        column = []
        for i in range(col_size):
            card = tableau_cards[offset + i]
            is_face_up = (i == col_size - 1)  # only last (bottom) card is face-up
            column.append({
                'card': card,
                'faceUp': is_face_up,
            })
        tableau.append(column)
        offset += col_size

    return {
        'tableau': tableau,
        'categoryTargets': category_targets,
        'handPile': hand_pile,
        'handDisplay': [],
    }


# ── Layout Quality Validation ────────────────────────────────────────────────

def try_greedy_drag(sim_tableau, sim_display, sim_slots, category_targets):
    """Try one greedy drag operation. Modifies sim state in-place. Returns True if a drag was made."""

    # Priority 1: face-up tableau card → matching slot (collect)
    for ci, col in enumerate(sim_tableau):
        if not col or not col[-1]['faceUp']:
            continue
        card = col[-1]['card']
        if card['type'] == 'regular':
            for si, s in enumerate(sim_slots):
                if s is not None and s['key'] == card['category'] and s['collected'] < s['target']:
                    col.pop()
                    s['collected'] += 1
                    if s['collected'] >= s['target']:
                        sim_slots[si] = None
                    # Auto-flip
                    if col and not col[-1]['faceUp']:
                        col[-1]['faceUp'] = True
                    return True

    # Priority 1b: face-up tableau gold → empty slot
    for ci, col in enumerate(sim_tableau):
        if not col or not col[-1]['faceUp']:
            continue
        card = col[-1]['card']
        if card['type'] == 'gold':
            for si, s in enumerate(sim_slots):
                if s is None:
                    col.pop()
                    sim_slots[si] = {
                        'key': card['category'],
                        'collected': 0,
                        'target': category_targets.get(card['category'], 0),
                    }
                    if col and not col[-1]['faceUp']:
                        col[-1]['faceUp'] = True
                    return True

    # Priority 1c: hand display top → matching slot
    if sim_display:
        top = sim_display[-1]
        if top['type'] == 'regular':
            for si, s in enumerate(sim_slots):
                if s is not None and s['key'] == top['category'] and s['collected'] < s['target']:
                    sim_display.pop()
                    s['collected'] += 1
                    if s['collected'] >= s['target']:
                        sim_slots[si] = None
                    return True
        if top['type'] == 'gold':
            for si, s in enumerate(sim_slots):
                if s is None:
                    sim_display.pop()
                    sim_slots[si] = {
                        'key': top['category'],
                        'collected': 0,
                        'target': category_targets.get(top['category'], 0),
                    }
                    return True

    # Priority 2: tableau → same-category column (stack)
    for ci, col in enumerate(sim_tableau):
        if not col or not col[-1]['faceUp']:
            continue
        card = col[-1]['card']
        if card['type'] == 'gold':
            continue  # gold cards don't stack on columns by category
        for ti, tcol in enumerate(sim_tableau):
            if ti == ci or not tcol:
                continue
            top_tc = tcol[-1]
            if top_tc['card']['type'] == 'gold':
                continue  # sealed
            if card['category'] == top_tc['card']['category']:
                tc = col.pop()
                tcol.append(tc)
                if col and not col[-1]['faceUp']:
                    col[-1]['faceUp'] = True
                return True

    # Priority 3: hand display → column (stack)
    if sim_display:
        top = sim_display[-1]
        for ti, tcol in enumerate(sim_tableau):
            if not tcol:
                # Can stack on empty column
                sim_display.pop()
                tcol.append({'card': top, 'faceUp': True})
                return True
            top_tc = tcol[-1]
            if top_tc['card']['type'] == 'gold':
                continue
            if top['category'] == top_tc['card']['category']:
                sim_display.pop()
                tcol.append({'card': top, 'faceUp': True})
                return True

    return False


def validate_layout(tableau, hand_pile, category_targets, max_slots):
    """Check 3 early-game quality conditions. Returns True if layout is good."""

    # ── 条件 3：金牌可及性 ──
    gold_accessible = False
    for col in tableau:
        if col and col[-1]['faceUp'] and col[-1]['card']['type'] == 'gold':
            gold_accessible = True
            break
    if not gold_accessible:
        for card in hand_pile[-5:]:
            if card['type'] == 'gold':
                gold_accessible = True
                break
    if not gold_accessible:
        return False

    # ── 条件 1：开局可操作 ──
    face_up_cards = []  # (colIdx, card)
    for ci, col in enumerate(tableau):
        if col and col[-1]['faceUp']:
            face_up_cards.append((ci, col[-1]['card']))

    has_immediate_move = False

    # 检查面朝上牌之间的交互
    for i, (ci, card_i) in enumerate(face_up_cards):
        # 金牌 → 可以进空槽
        if card_i['type'] == 'gold':
            has_immediate_move = True
            break
        # 同类别牌 → 可以叠放
        for j, (cj, card_j) in enumerate(face_up_cards):
            if i != j and card_i['category'] == card_j['category']:
                has_immediate_move = True
                break
        if has_immediate_move:
            break

    if not has_immediate_move:
        # 检查手牌顶部 2 张（pop从末尾取，所以检查末尾）
        for card in hand_pile[-2:]:
            if card['type'] == 'gold':
                has_immediate_move = True
                break
            for ci, fu_card in face_up_cards:
                if card['category'] == fu_card['category']:
                    has_immediate_move = True
                    break
            if has_immediate_move:
                break

    if not has_immediate_move:
        return False

    # ── 条件 2：前期流畅性（贪心模拟）──
    # 深拷贝状态进行模拟
    sim_tableau = [[{'card': dict(tc['card']), 'faceUp': tc['faceUp']} for tc in col] for col in tableau]
    sim_hand = [dict(c) for c in hand_pile]
    sim_display = []
    sim_slots = [None] * max_slots

    drag_count = 0
    consec_flips = 0

    for step in range(20):  # 最多模拟 20 步
        if drag_count >= 5:
            break  # 已满 5 次拖动，通过

        # 尝试找拖动操作（贪心优先级）
        did_drag = try_greedy_drag(sim_tableau, sim_display, sim_slots, category_targets)

        if did_drag:
            drag_count += 1
            consec_flips = 0
        else:
            # 翻手牌（从末尾取，与求解器一致）
            if sim_hand:
                sim_display.append(sim_hand.pop())
                consec_flips += 1
                if consec_flips > 3:
                    return False  # 连续翻牌超过 3 次
            else:
                break  # 手牌空了

    return True


# ── Move Stats Helper ────────────────────────────────────────────────────

def empty_move_stats():
    """Return a fresh move stats dict with all 7 operation types zeroed."""
    return {
        'colSingleToSlot': 0,   # 1. 列顶牌→收集槽（单张）
        'colMultiToSlot': 0,    # 2. 列→收集槽（多张拖动）
        'colToCol': 0,          # 3. 列牌→另一列（单张叠放）
        'colMultiToCol': 0,     # 3b. 列→另一列（多张叠放）
        'handToSlot': 0,        # 4. 手牌展示区顶牌→收集槽
        'handToCol': 0,         # 5. 手牌展示区顶牌→列
        'flip': 0,              # 6. 翻手牌
        'recycle': 0,           # 7. 回收手牌
    }

def classify_move(move_type):
    """Map internal move type to one of the 7 operation categories."""
    if move_type in ('tableau_to_slot', 'tableau_gold_to_slot'):
        return 'colSingleToSlot'
    if move_type == 'tableau_multi_to_slot':
        return 'colMultiToSlot'
    if move_type == 'tableau_to_column':
        return 'colToCol'
    if move_type == 'tableau_multi_to_column':
        return 'colMultiToCol'
    if move_type in ('display_to_slot', 'display_gold_to_slot'):
        return 'handToSlot'
    if move_type == 'display_to_column':
        return 'handToCol'
    if move_type == 'flip_hand':
        return 'flip'
    if move_type == 'recycle':
        return 'recycle'
    return None


# ── Solver Constants ──────────────────────────────────────────────────────

MAX_RECYCLES = 3

# 决策树参数（仿竞品硬编码常量）
MAX_TREE_DEPTH = 8          # 决策树最大搜索深度
