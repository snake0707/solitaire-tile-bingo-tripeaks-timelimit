def solve_level(tableau, category_targets, max_steps, max_slots, hand_pile, conservative=False, display_steps=None, reject_greedy_ties=False):
    """Priority + Equality backtracking solver (inspired by competitor approach).

    Two-phase per attempt:
      Phase 1 (Greedy): first GREEDY_PHASE_RATIO of display_steps — pure greedy, no backtracking.
                         If stuck here → layout invalid (return None for this attempt).
      Phase 2 (Backtracking): remaining steps — decision tree with backtracking allowed.

    Two strategies across multiple rounds:
      1. Priority Strategy: greedy with backtracking, weighted move selection
      2. Equality Strategy: unbiased DFS with backtracking

    Args:
        conservative: If True, use conservative gold card rules:
          - display_gold_to_slot: only if tableau has face-up regular of same category
          - gold column-to-column: only if category fully collected
          - display gold to column: only if free_slots > 0 or category fully collected
        display_steps: Player-facing step count for greedy phase threshold.
                       If None, defaults to max_steps.

    Returns: { 'won': bool, 'stepsUsed': int, 'moveStats': dict,
               'strategyType': 'priority'|'equality', 'nodesExplored': int }
    """
    # Deep clone state
    state = {
        'tableau': [[{'card': dict(tc['card']), 'faceUp': tc['faceUp']} for tc in col] for col in tableau],
        'slots': [None] * max_slots,
        'stepsLeft': max_steps,
        'completedCount': 0,
        'numCategories': len(category_targets),
        'handPile': [dict(c) for c in hand_pile],
        'handDisplay': [],
        'recycleCount': 0,
    }

    # Greedy phase threshold: first N steps are pure greedy (no backtracking)
    _display = display_steps if display_steps is not None else max_steps
    greedy_step_limit = int(_display * GREEDY_PHASE_RATIO)

    nodes_explored = [0]
    seen_since_drag = set()  # Track hand cards seen since last successful drag (for soft deadlock)

    def get_top_card(col):
        return col[-1] if col else None

    # ── Conservative mode helpers ──
    def _has_tableau_regular_for(cat):
        """Check if tableau has any face-up regular card of the given category."""
        for col in state['tableau']:
            for tc in col:
                if tc['faceUp'] and tc['card']['type'] == 'regular' and tc['card']['category'] == cat:
                    return True
        return False

    def _is_cat_completed(cat):
        """Check if category's regular cards are fully collected in slots."""
        for s in state['slots']:
            if s is not None and s['key'] == cat and s['collected'] >= s['target']:
                return True
        return False

    def _is_cat_all_regulars_on_tableau(cat):
        """Check if all regular cards of a category are face-up on a single tableau column."""
        target = category_targets.get(cat, 0)
        if target <= 0:
            return False
        for col in state['tableau']:
            count = 0
            for tc in col:
                if tc['faceUp'] and tc['card']['type'] == 'regular' and tc['card']['category'] == cat:
                    count += 1
            if count >= target:
                return True
        return False

    def get_moves():
        moves = []
        has_empty_slot = any(s is None for s in state['slots'])

        # Tableau top cards → slot (single and multi-card)
        for ci in range(len(state['tableau'])):
            col = state['tableau'][ci]
            top = get_top_card(col)
            if not top or not top['faceUp']:
                continue

            # Check multi-card drag first
            top_idx = len(col) - 1
            cat = col[top_idx]['card']['category']
            start_idx = top_idx
            while start_idx > 0 and col[start_idx - 1]['faceUp'] and col[start_idx - 1]['card']['category'] == cat:
                start_idx -= 1
            drag_count = top_idx - start_idx + 1

            added_multi = False
            if drag_count >= 2:
                # Case A: gold on top + regulars below
                if col[top_idx]['card']['type'] == 'gold' and has_empty_slot:
                    all_regular_below = all(col[i]['card']['type'] == 'regular' for i in range(start_idx, top_idx))
                    if all_regular_below:
                        moves.append({'type': 'tableau_multi_to_slot', 'colIdx': ci, 'startIdx': start_idx, 'count': drag_count})
                        added_multi = True


                # Case C: gold on bottom + regulars above → to empty slot
                if not added_multi and col[start_idx]['card']['type'] == 'gold' and has_empty_slot:
                    all_regular_above = all(col[i]['card']['type'] == 'regular' for i in range(start_idx + 1, top_idx + 1))
                    if all_regular_above:
                        moves.append({'type': 'tableau_multi_to_slot', 'colIdx': ci, 'startIdx': start_idx, 'count': drag_count})
                        added_multi = True
                if not added_multi and all(col[i]['card']['type'] == 'regular' for i in range(start_idx, top_idx + 1)):
                    for si, s in enumerate(state['slots']):
                        if s is not None and s['key'] == cat and s['collected'] + drag_count <= s['target']:
                            moves.append({'type': 'tableau_multi_to_slot', 'colIdx': ci, 'startIdx': start_idx, 'count': drag_count})
                            added_multi = True
                            break

            # Single card moves (skip if multi-to-slot already covers this card)
            if top["card"]["type"] == "regular" and not added_multi:
                slot_idx = None
                for si, s in enumerate(state['slots']):
                    if s is not None and s['key'] == top['card']['category'] and s['collected'] < s['target']:
                        slot_idx = si
                        break
                if slot_idx is not None:
                    moves.append({'type': 'tableau_to_slot', 'colIdx': ci, 'slotIdx': slot_idx})

            if top['card']['type'] == 'gold' and has_empty_slot and not added_multi:
                moves.append({'type': 'tableau_gold_to_slot', 'colIdx': ci})

        # Hand display → slot
        if state['handDisplay']:
            top_card = state['handDisplay'][-1]
            if top_card['type'] == 'regular':
                slot_idx = None
                for si, s in enumerate(state['slots']):
                    if s is not None and s['key'] == top_card['category'] and s['collected'] < s['target']:
                        slot_idx = si
                        break
                if slot_idx is not None:
                    moves.append({'type': 'display_to_slot', 'slotIdx': slot_idx})

            if top_card['type'] == 'gold' and has_empty_slot:
                if not conservative or _has_tableau_regular_for(top_card['category']):
                    moves.append({'type': 'display_gold_to_slot'})

        # Tableau → column (single card)
        for ci in range(len(state['tableau'])):
            col = state['tableau'][ci]
            top = get_top_card(col)
            if not top or not top['faceUp']:
                continue
            for ti in range(len(state['tableau'])):
                if ti == ci:
                    continue
                # Conservative: gold cards can only move column-to-column if category completed
                # Exception: allow if source has face-down card AND target is empty (reveal hidden, don't seal basics)
                if conservative and top['card']['type'] == 'gold' and not _is_cat_all_regulars_on_tableau(top['card']['category']):
                    has_facedown = len(col) >= 2 and not col[-2]['faceUp']
                    if not (has_facedown and len(state['tableau'][ti]) == 0):
                        continue
                if can_stack_on_column(top['card'], state['tableau'][ti]):
                    moves.append({'type': 'tableau_to_column', 'srcCol': ci, 'dstCol': ti})

        # Tableau → column (multi-card: consecutive same-category face-up cards ≥2)
        for ci in range(len(state['tableau'])):
            col = state['tableau'][ci]
            if not col:
                continue
            top_idx = len(col) - 1
            if not col[top_idx]['faceUp']:
                continue
            cat = col[top_idx]['card']['category']
            start_idx = top_idx
            while start_idx > 0 and col[start_idx - 1]['faceUp'] and col[start_idx - 1]['card']['category'] == cat:
                start_idx -= 1
            drag_count = top_idx - start_idx + 1
            if drag_count < 2:
                continue
            bottom_card = col[start_idx]['card']
            for ti in range(len(state['tableau'])):
                if ti == ci:
                    continue
                # Conservative: gold cards can only move column-to-column if category completed
                # Exception: allow if source has face-down card AND target is empty
                if conservative and col[top_idx]['card']['type'] == 'gold' and not _is_cat_all_regulars_on_tableau(cat):
                    has_facedown = start_idx > 0 and not col[start_idx - 1]['faceUp']
                    if not (has_facedown and len(state['tableau'][ti]) == 0):
                        continue
                if can_stack_on_column(bottom_card, state['tableau'][ti]):
                    moves.append({'type': 'tableau_multi_to_column', 'srcCol': ci, 'dstCol': ti, 'startIdx': start_idx, 'count': drag_count})

        # Hand display → column
        if state['handDisplay']:
            top_card = state['handDisplay'][-1]
            # Conservative: gold in hand + no free slots → only if category completed
            free_slots_now = sum(1 for s in state['slots'] if s is None)
            skip_gold_col = conservative and top_card['type'] == 'gold' and free_slots_now == 0 and not _is_cat_all_regulars_on_tableau(top_card['category'])
            for ti in range(len(state['tableau'])):
                if not skip_gold_col and can_stack_on_column(top_card, state['tableau'][ti]):
                    moves.append({'type': 'display_to_column', 'dstCol': ti})

        # Flip hand
        if state['handPile']:
            moves.append({'type': 'flip_hand'})

        # Recycle
        if not state['handPile'] and state['handDisplay'] and state['recycleCount'] < MAX_RECYCLES:
            moves.append({'type': 'recycle'})

        return moves

    def auto_flip(col):
        if col and not col[-1]['faceUp']:
            col[-1]['faceUp'] = True
            return True
        return False

    def apply_move(move):
        undo = {'type': move['type']}

        if move['type'] == 'tableau_multi_to_slot':
            state['stepsLeft'] -= 1
            col = state['tableau'][move['colIdx']]
            start_idx = move['startIdx']
            removed = col[start_idx:]
            del col[start_idx:]
            undo['colIdx'] = move['colIdx']
            undo['removed'] = removed
            undo['startIdx'] = start_idx

            top_card = removed[-1]
            bottom_card = removed[0]
            # Gold on top (Case A) or gold on bottom (Case C)
            gold_card = None
            if top_card['card']['type'] == 'gold':
                gold_card = top_card
            elif bottom_card['card']['type'] == 'gold':
                gold_card = bottom_card
            if gold_card is not None:
                empty_idx = next(i for i, s in enumerate(state['slots']) if s is None)
                regular_count = len(removed) - 1
                target = category_targets.get(gold_card['card']['category'], 0)
                state['slots'][empty_idx] = {
                    'key': gold_card['card']['category'],
                    'collected': regular_count,
                    'target': target,
                }
                undo['slotIdx'] = empty_idx
                undo['slotWasNone'] = True
                if regular_count >= target:
                    undo['completed'] = dict(state['slots'][empty_idx])
                    state['slots'][empty_idx] = None
                    state['completedCount'] += 1
            else:
                cat = removed[0]['card']['category']
                for si, s in enumerate(state['slots']):
                    if s is not None and s['key'] == cat:
                        undo['slotIdx'] = si
                        undo['slotWasNone'] = False
                        undo['prevCollected'] = s['collected']
                        s['collected'] += len(removed)
                        if s['collected'] >= s['target']:
                            undo['completed'] = dict(s)
                            state['slots'][si] = None
                            state['completedCount'] += 1
                        break
            undo['flipped'] = auto_flip(col)

        elif move['type'] == 'tableau_to_slot':
            state['stepsLeft'] -= 1
            col = state['tableau'][move['colIdx']]
            tc = col.pop()
            undo['colIdx'] = move['colIdx']
            undo['tc'] = tc
            undo['slotIdx'] = move['slotIdx']

            slot = state['slots'][move['slotIdx']]
            undo['prevCollected'] = slot['collected']
            slot['collected'] += 1
            if slot['collected'] >= slot['target']:
                undo['completed'] = dict(slot)
                state['slots'][move['slotIdx']] = None
                state['completedCount'] += 1
            undo['flipped'] = auto_flip(col)

        elif move['type'] == 'tableau_gold_to_slot':
            state['stepsLeft'] -= 1
            col = state['tableau'][move['colIdx']]
            tc = col.pop()
            undo['colIdx'] = move['colIdx']
            undo['tc'] = tc

            empty_idx = next(i for i, s in enumerate(state['slots']) if s is None)
            state['slots'][empty_idx] = {
                'key': tc['card']['category'],
                'collected': 0,
                'target': category_targets.get(tc['card']['category'], 0),
            }
            undo['slotIdx'] = empty_idx
            undo['flipped'] = auto_flip(col)

        elif move['type'] == 'display_to_slot':
            state['stepsLeft'] -= 1
            card = state['handDisplay'].pop()
            undo['card'] = card
            undo['slotIdx'] = move['slotIdx']

            slot = state['slots'][move['slotIdx']]
            undo['prevCollected'] = slot['collected']
            slot['collected'] += 1
            if slot['collected'] >= slot['target']:
                undo['completed'] = dict(slot)
                state['slots'][move['slotIdx']] = None
                state['completedCount'] += 1

        elif move['type'] == 'display_gold_to_slot':
            state['stepsLeft'] -= 1
            card = state['handDisplay'].pop()
            undo['card'] = card
            empty_idx = next(i for i, s in enumerate(state['slots']) if s is None)
            state['slots'][empty_idx] = {
                'key': card['category'],
                'collected': 0,
                'target': category_targets.get(card['category'], 0),
            }
            undo['slotIdx'] = empty_idx

        elif move['type'] == 'tableau_to_column':
            state['stepsLeft'] -= 1
            src_col = state['tableau'][move['srcCol']]
            tc = src_col.pop()
            undo['srcCol'] = move['srcCol']
            undo['dstCol'] = move['dstCol']
            undo['tc'] = tc
            state['tableau'][move['dstCol']].append(tc)
            undo['flipped'] = auto_flip(src_col)

        elif move['type'] == 'tableau_multi_to_column':
            state['stepsLeft'] -= 1
            src_col = state['tableau'][move['srcCol']]
            start_idx = move['startIdx']
            removed = src_col[start_idx:]
            del src_col[start_idx:]
            undo['srcCol'] = move['srcCol']
            undo['dstCol'] = move['dstCol']
            undo['removed'] = removed
            undo['startIdx'] = start_idx
            state['tableau'][move['dstCol']].extend(removed)
            undo['flipped'] = auto_flip(src_col)

        elif move['type'] == 'display_to_column':
            state['stepsLeft'] -= 1
            card = state['handDisplay'].pop()
            undo['card'] = card
            undo['dstCol'] = move['dstCol']
            state['tableau'][move['dstCol']].append({'card': card, 'faceUp': True})

        elif move['type'] == 'flip_hand':
            state['stepsLeft'] -= 1
            card = state['handPile'].pop()
            state['handDisplay'].append(card)
            undo['card'] = card

        elif move['type'] == 'recycle':
            state['stepsLeft'] -= 1
            undo['displaySnapshot'] = list(state['handDisplay'])
            state['handPile'] = list(reversed(state['handDisplay']))
            state['handDisplay'] = []
            state['recycleCount'] += 1

        return undo

    def undo_move(undo):
        if undo['type'] == 'tableau_multi_to_slot':
            state['stepsLeft'] += 1
            col = state['tableau'][undo['colIdx']]
            if undo.get('flipped'):
                col[-1]['faceUp'] = False
            col.extend(undo['removed'])
            if 'completed' in undo:
                state['completedCount'] -= 1
            if undo['slotWasNone']:
                si = undo['slotIdx']
                state['slots'][si] = None
            else:
                si = undo['slotIdx']
                if state['slots'][si] is None and 'completed' in undo:
                    state['slots'][si] = undo['completed']
                state['slots'][si]['collected'] = undo['prevCollected']

        elif undo['type'] == 'tableau_to_slot':
            state['stepsLeft'] += 1
            col = state['tableau'][undo['colIdx']]
            if undo.get('flipped'):
                col[-1]['faceUp'] = False
            col.append(undo['tc'])
            if 'completed' in undo:
                state['completedCount'] -= 1
                state['slots'][undo['slotIdx']] = undo['completed']
                state['slots'][undo['slotIdx']]['collected'] = undo['prevCollected']
            else:
                state['slots'][undo['slotIdx']]['collected'] -= 1

        elif undo['type'] == 'tableau_gold_to_slot':
            state['stepsLeft'] += 1
            col = state['tableau'][undo['colIdx']]
            if undo.get('flipped'):
                col[-1]['faceUp'] = False
            col.append(undo['tc'])
            state['slots'][undo['slotIdx']] = None

        elif undo['type'] == 'display_to_slot':
            state['stepsLeft'] += 1
            if 'completed' in undo:
                state['completedCount'] -= 1
                state['slots'][undo['slotIdx']] = undo['completed']
                state['slots'][undo['slotIdx']]['collected'] = undo['prevCollected']
            else:
                state['slots'][undo['slotIdx']]['collected'] -= 1
            state['handDisplay'].append(undo['card'])

        elif undo['type'] == 'display_gold_to_slot':
            state['stepsLeft'] += 1
            state['slots'][undo['slotIdx']] = None
            state['handDisplay'].append(undo['card'])

        elif undo['type'] == 'tableau_to_column':
            state['stepsLeft'] += 1
            state['tableau'][undo['dstCol']].pop()
            if undo.get('flipped'):
                state['tableau'][undo['srcCol']][-1]['faceUp'] = False
            state['tableau'][undo['srcCol']].append(undo['tc'])

        elif undo['type'] == 'tableau_multi_to_column':
            state['stepsLeft'] += 1
            dst_col = state['tableau'][undo['dstCol']]
            count = len(undo['removed'])
            del dst_col[-count:]
            if undo.get('flipped'):
                state['tableau'][undo['srcCol']][-1]['faceUp'] = False
            state['tableau'][undo['srcCol']].extend(undo['removed'])

        elif undo['type'] == 'display_to_column':
            state['stepsLeft'] += 1
            state['tableau'][undo['dstCol']].pop()
            state['handDisplay'].append(undo['card'])

        elif undo['type'] == 'flip_hand':
            state['stepsLeft'] += 1
            state['handDisplay'].pop()
            state['handPile'].append(undo['card'])

        elif undo['type'] == 'recycle':
            state['stepsLeft'] += 1
            state['handDisplay'] = undo['displaySnapshot']
            state['handPile'] = []
            state['recycleCount'] -= 1

    def get_priority_weight(move):
        """Calculate priority weight for a move.

        New weight system (2026-04-02):
          16: 完成类别（释放槽位）
          14: 桌面牌收集（纯基础牌）
          12: 手牌收集（基础牌）
          10: 桌面牌收集（包含类别牌）
           8: 手牌收集（类别牌，桌面有对应基础牌）
           6: 列间移动，翻出暗牌
           4: 手牌移动到列
           3: 列间移动，不翻暗牌（归拢同类别）
           2: 翻手牌
           1: 手牌回收
           0: 不执行（源列无暗牌+目标空列）
        """
        mt = move['type']

        # ── 桌面牌 → 收集区（regular 单张）──
        if mt == 'tableau_to_slot':
            card = state['tableau'][move['colIdx']][-1]['card']
            for s in state['slots']:
                if s is not None and s['key'] == card['category']:
                    if s['collected'] + 1 >= s['target']:
                        return 16  # 完成类别
                    break
            return 14  # 桌面基础牌归类

        # ── 桌面牌 → 收集区（gold 单张）──
        if mt == 'tableau_gold_to_slot':
            return 10  # 桌面类别牌

        # ── 桌面牌 → 收集区（批量 multi）──
        if mt == 'tableau_multi_to_slot':
            col = state['tableau'][move['colIdx']]
            start_idx = move.get('startIdx', 0)
            top_card = col[-1]
            bottom_card = col[start_idx]
            is_gold_move = top_card['card']['type'] == 'gold' or bottom_card['card']['type'] == 'gold'
            num_cards = len(col) - start_idx

            if is_gold_move:
                # Check if gold multi completes the category
                cat_key = col[-1]['card']['category']
                num_regulars = num_cards - 1  # exclude the gold card
                target = category_targets.get(cat_key, 0)
                if num_regulars >= target:
                    return 16  # 完成类别
                return 10  # 桌面含类别牌收集
            else:
                # All regular → check if completes
                cat_key = col[-1]['card']['category']
                for s in state['slots']:
                    if s is not None and s['key'] == cat_key:
                        if s['collected'] + num_cards >= s['target']:
                            return 16  # 完成类别
                        break
                return 14  # 桌面基础牌归类

        # ── 手牌 → 收集区（regular）──
        if mt == 'display_to_slot':
            card = state['handDisplay'][-1]
            for s in state['slots']:
                if s is not None and s['key'] == card['category']:
                    if s['collected'] + 1 >= s['target']:
                        return 16  # 完成类别
                    break
            return 12  # 手牌基础牌归类

        # ── 手牌 → 收集区（gold）──
        if mt == 'display_gold_to_slot':
            return 8  # 手牌类别牌

        # ── 列间移动 ──
        if mt == 'tableau_to_column':
            col = state['tableau'][move['srcCol']]
            dst_col = state['tableau'][move['dstCol']]
            has_facedown = len(col) >= 2 and not col[-2]['faceUp']
            top_card = col[-1]['card']
            if not has_facedown and len(dst_col) == 0:
                return 0  # 无暗牌+目标空列，不移动
            if has_facedown:
                # 金牌移动到空列翻暗牌：权重5（低于基础牌翻暗牌6，高于手牌入列4）
                if top_card['type'] == 'gold' and len(dst_col) == 0:
                    return 5
                return 6  # 翻暗牌
            return 3  # 不翻暗牌，归拢同类别

        if mt == 'tableau_multi_to_column':
            col = state['tableau'][move['srcCol']]
            dst_col = state['tableau'][move['dstCol']]
            start_idx = move['startIdx']
            has_facedown = start_idx > 0 and not col[start_idx - 1]['faceUp']
            top_card = col[-1]['card']
            if not has_facedown and len(dst_col) == 0:
                return 0
            if has_facedown:
                # 金牌（在 multi 顶部）移动到空列翻暗牌：权重5
                if top_card['type'] == 'gold' and len(dst_col) == 0:
                    return 5
                return 6
            return 3

        # ── 手牌 → 桌面列 ──
        if mt == 'display_to_column':
            return 4

        # ── 翻手牌 / 回收 ──
        if mt == 'flip_hand':
            return 2
        if mt == 'recycle':
            return 1

        return 0

    def solve_with_backtracking(use_priority):
        """Two-phase solver: greedy phase → backtracking phase.

        Phase 1 (Greedy): first greedy_step_limit steps — pure greedy, no backtracking.
                           If stuck here → return None (layout invalid for this attempt).
        Phase 2 (Backtracking): after greedy phase — decision tree with backtracking allowed.

        Args:
            use_priority: True for Priority Strategy (weighted), False for Equality Strategy (DFS order)

        Returns: { 'won': bool, 'stepsUsed': int, 'moveStats': dict, 'nodesExplored': int } or None
        """
        total_steps = [0]
        move_sequence = []  # track move types for stats
        move_path = []      # track full move dicts for path output

        # Stack-based decision tree
        # Each node: { 'candidates': list, 'index': int, 'undo': undo_info, 'move': move }
        stack = []

        def _count_facedown(col_idx):
            """Count face-down cards in a column."""
            return sum(1 for tc in state['tableau'][col_idx] if not tc['faceUp'])

        def _get_tiebreak_key(move):
            """Secondary sort key within same weight. Lower = higher priority."""
            w = get_priority_weight(move)
            mt = move['type']

            # Weight 6 (列间移动翻暗牌): source with fewer face-down first
            if w == 6:
                src = move.get('srcCol', 0)
                return _count_facedown(src)

            # Weight 14 (桌面基础牌归类): source with fewer face-down first
            if w == 14:
                src = move.get('colIdx', 0)
                return _count_facedown(src)

            # Weight 10 (桌面含类别牌收集): source with fewer face-down first
            if w == 10:
                src = move.get('colIdx', 0)
                return _count_facedown(src)

            # Weight 3 (列间归拢同类别): prefer target column with more same-category cards
            if w == 3:
                dst = move.get('dstCol', 0)
                dst_col = state['tableau'][dst]
                card_cat = None
                if mt == 'tableau_to_column':
                    card_cat = state['tableau'][move['srcCol']][-1]['card']['category']
                elif mt == 'tableau_multi_to_column':
                    card_cat = state['tableau'][move['srcCol']][move['startIdx']]['card']['category']
                if card_cat:
                    same_count = sum(1 for tc in dst_col if tc['faceUp'] and tc['card']['category'] == card_cat)
                    return -same_count  # more same-category = lower key = higher priority
                return 0

            # Weight 4 (手牌放列): prefer target column with more same-category cards
            if w == 4:
                dst = move.get('dstCol', 0)
                dst_col = state['tableau'][dst]
                if state['handDisplay']:
                    card_cat = state['handDisplay'][-1]['category']
                    same_count = sum(1 for tc in dst_col if tc['faceUp'] and tc['card']['category'] == card_cat)
                    return -same_count
                return 0

            # All other weights: no tiebreak (random)
            return 0

        def get_sorted_candidates():
            """Get candidate moves, sorted by weight (priority) or original order (equality).
            Within same weight, apply tiebreak rules."""
            moves = get_moves()
            if not moves:
                return []
            # Limit branches
            if len(moves) > MAX_POSSIBLE_MOVES:
                moves = moves[:MAX_POSSIBLE_MOVES]
            if use_priority:
                moves.sort(key=lambda m: (-get_priority_weight(m), _get_tiebreak_key(m)))
            return moves

        def _pick_greedy_move(moves, reject_ties=False):
            """Pick one greedy move: highest weight + tiebreak, random among ties.
            If reject_ties=True and use_priority, return None when multiple equal candidates exist."""
            if use_priority:
                moves.sort(key=lambda m: (-get_priority_weight(m), _get_tiebreak_key(m)))
                top_w = get_priority_weight(moves[0])
                top_tb = _get_tiebreak_key(moves[0])
                top_count = 1
                while top_count < len(moves) and get_priority_weight(moves[top_count]) == top_w and _get_tiebreak_key(moves[top_count]) == top_tb:
                    top_count += 1
                if reject_ties and top_count > 1:
                    return None
                return moves[random.randint(0, top_count - 1)]
            else:
                return moves[random.randint(0, len(moves) - 1)]

        def _too_many_consecutive_flips(seq):
            """Check if the last MAX_CONSECUTIVE_FLIPS moves in seq are all flip_hand."""
            if len(seq) < MAX_CONSECUTIVE_FLIPS:
                return False
            return all(seq[-i-1] == 'flip_hand' for i in range(MAX_CONSECUTIVE_FLIPS))

        def _too_many_flip_drags(seq):
            """Check if recent moves have too many consecutive flip-drag pairs.
            Two-tier: always check both absolute limit and strict limit separately."""
            _drag_types = {'display_to_slot', 'display_to_column', 'display_gold_to_slot'}
            def _check_limit(s, limit):
                n = limit * 2
                if len(s) < n:
                    return False
                for i in range(limit):
                    flip_idx = len(s) - n + i * 2
                    drag_idx = flip_idx + 1
                    if s[flip_idx] != 'flip_hand' or s[drag_idx] not in _drag_types:
                        return False
                return True
            # Absolute limit: always check
            if _check_limit(seq, MAX_CONSECUTIVE_FLIP_DRAGS):
                return True
            # Strict limit: check if hand/tableau thresholds met at the START of the streak
            if len(seq) >= MAX_FLIP_DRAGS_STRICT * 2 and _check_limit(seq, MAX_FLIP_DRAGS_STRICT):
                # Estimate state at streak start:
                # - hand: each flip consumed 1 from pile → start = current + limit
                # - tableau: display_to_column adds 1 → start = current - count_of_display_to_column_in_streak
                n = MAX_FLIP_DRAGS_STRICT * 2
                hand_at_start = len(state['handPile']) + MAX_FLIP_DRAGS_STRICT
                col_moves = sum(1 for i in range(len(seq) - n, len(seq)) if seq[i] == 'display_to_column')
                tableau_at_start = sum(len(col) for col in state['tableau']) - col_moves
                if hand_at_start >= FLIP_DRAG_HAND_THRESHOLD and tableau_at_start >= FLIP_DRAG_TABLEAU_THRESHOLD:
                    return True
            return False

        def _is_soft_deadlock():
            """Check if we're in a soft deadlock: all hand cards have been seen
            since last successful drag, and no tableau or hand moves can collect."""
            total_hand = len(state['handPile']) + len(state['handDisplay'])
            if len(seen_since_drag) < total_hand:
                return False
            # Check if any tableau top card can go to slot or move between columns
            for ci, col in enumerate(state['tableau']):
                if not col or not col[-1]['faceUp']:
                    continue
                top = col[-1]['card']
                # Can go to slot?
                if top['type'] == 'regular':
                    for s in state['slots']:
                        if s is not None and s['key'] == top['category'] and s['collected'] < s['target']:
                            return False
                if top['type'] == 'gold' and any(s is None for s in state['slots']):
                    return False
                # Can move to another column? (skip weight=0: no facedown + empty target)
                has_facedown = len(col) >= 2 and not col[-2]['faceUp']
                for ti, tcol in enumerate(state['tableau']):
                    if ti == ci:
                        continue
                    if not has_facedown and len(tcol) == 0:
                        continue  # pointless move, ignore
                    if can_stack_on_column(top, tcol):
                        return False
            # Check if any hand display card can go to slot or column
            if state['handDisplay']:
                hc = state['handDisplay'][-1]
                if hc['type'] == 'regular':
                    for s in state['slots']:
                        if s is not None and s['key'] == hc['category'] and s['collected'] < s['target']:
                            return False
                if hc['type'] == 'gold' and any(s is None for s in state['slots']):
                    return False
                for ti, tcol in enumerate(state['tableau']):
                    if can_stack_on_column(hc, tcol):
                        return False
            return True

        def greedy_playout():
            """Play greedily to completion or deadlock. Returns (won, undos, move_types, move_dicts).
            Uses tiebreak rules within same weight, random only among equal-tiebreak moves."""
            undos = []
            mtypes = []
            mdicts = []
            won = False
            seen_since_drag.clear()
            while state['stepsLeft'] > 0:
                if state['completedCount'] >= state['numCategories']:
                    won = True
                    break
                moves = get_moves()
                if not moves:
                    break
                move = _pick_greedy_move(moves)
                undos.append(apply_move(move))
                mtypes.append(move['type'])
                mdicts.append(dict(move))
                total_steps[0] += 1
                nodes_explored[0] += 1
                # Soft deadlock tracking
                mt = move['type']
                if mt == 'flip_hand':
                    # Add the flipped card to seen set (it's now top of handDisplay)
                    if state['handDisplay']:
                        seen_since_drag.add(id(state['handDisplay'][-1]))
                    if _is_soft_deadlock():
                        break
                    # Check consecutive flips across move_sequence + mtypes
                    if _too_many_consecutive_flips(move_sequence + mtypes):
                        won = False
                        break
                elif mt != 'recycle':
                    # Any non-flip, non-recycle move = board changed, reset tracking
                    seen_since_drag.clear()
                # Consecutive flip-drag check
                if mt in ('display_to_slot', 'display_to_column', 'display_gold_to_slot'):
                    if _too_many_flip_drags(move_sequence + mtypes):
                        won = False
                        break
                # recycle: don't clear (same cards, seen is seen)
                if total_steps[0] > MAX_SOLVER_STEPS:
                    break
            return won, undos, mtypes, mdicts

        def _build_result(seq, path):
            """Build result dict from move sequence and path."""
            steps_used = max_steps - state['stepsLeft']
            ms = empty_move_stats()
            for mt in seq:
                cat = classify_move(mt)
                if cat:
                    ms[cat] += 1
            return {'won': True, 'stepsUsed': steps_used, 'moveStats': ms,
                    'nodesExplored': nodes_explored[0], 'movePath': list(path)}

        # ════════════════════════════════════════════════════════════
        # Phase 1: Greedy phase — pure greedy for first greedy_step_limit steps
        # ════════════════════════════════════════════════════════════
        greedy_undos = []
        seen_since_drag.clear()
        greedy_phase_ok = True

        while state['stepsLeft'] > 0 and total_steps[0] <= MAX_SOLVER_STEPS:
            if state['completedCount'] >= state['numCategories']:
                # Won during greedy phase!
                result = _build_result(move_sequence, move_path)
                for u in reversed(greedy_undos):
                    undo_move(u)
                move_sequence.clear()
                move_path.clear()
                return result

            steps_used = max_steps - state['stepsLeft']
            if steps_used >= greedy_step_limit:
                break  # Greedy phase done, enter backtracking phase

            moves = get_moves()
            if not moves:
                greedy_phase_ok = False
                break

            move = _pick_greedy_move(moves, reject_ties=(reject_greedy_ties and use_priority))
            if move is None:
                greedy_phase_ok = False
                break
            greedy_undos.append(apply_move(move))
            move_sequence.append(move['type'])
            move_path.append(dict(move))
            total_steps[0] += 1
            nodes_explored[0] += 1

            # Soft deadlock tracking
            mt = move['type']
            if mt == 'flip_hand':
                if state['handDisplay']:
                    seen_since_drag.add(id(state['handDisplay'][-1]))
                if _is_soft_deadlock():
                    greedy_phase_ok = False
                    break
                if _too_many_consecutive_flips(move_sequence):
                    greedy_phase_ok = False
                    break
            elif mt != 'recycle':
                seen_since_drag.clear()

            # Consecutive flip-drag check (after drag moves)
            if mt in ('display_to_slot', 'display_to_column', 'display_gold_to_slot'):
                if _too_many_flip_drags(move_sequence):
                    greedy_phase_ok = False
                    break

        if not greedy_phase_ok:
            # Stuck in greedy phase → layout invalid, undo and return None
            for u in reversed(greedy_undos):
                undo_move(u)
            move_sequence.clear()
            move_path.clear()
            return None

        # Save greedy phase state for restoration after backtracking
        greedy_seq = list(move_sequence)
        greedy_path = list(move_path)

        # ════════════════════════════════════════════════════════════
        # Phase 2: Backtracking phase — decision tree from current state
        # ════════════════════════════════════════════════════════════

        # Initial candidates
        candidates = get_sorted_candidates()
        if not candidates:
            # No moves at start of phase 2 — undo greedy and fail
            for u in reversed(greedy_undos):
                undo_move(u)
            move_sequence.clear()
            move_path.clear()
            return None

        # Try first candidate, push to stack
        move = candidates[0]
        undo = apply_move(move)
        move_sequence.append(move['type'])
        move_path.append(dict(move))
        total_steps[0] += 1
        nodes_explored[0] += 1
        stack.append({'candidates': candidates, 'index': 0, 'undo': undo, 'move': move})

        while stack and total_steps[0] <= MAX_SOLVER_STEPS:
            # Check win
            if state['completedCount'] >= state['numCategories']:
                result = _build_result(move_sequence, move_path)
                # Undo backtracking stack
                for node in reversed(stack):
                    undo_move(node['undo'])
                # Undo greedy phase
                for u in reversed(greedy_undos):
                    undo_move(u)
                move_sequence.clear()
                move_path.clear()
                return result

            depth = len(stack)

            # Too many consecutive flips or flip-drags → treat as dead end, backtrack
            if _too_many_consecutive_flips(move_sequence) or _too_many_flip_drags(move_sequence):
                pass  # fall through to backtrack
            elif depth < MAX_TREE_DEPTH:
                # Expand: get candidates at this state
                candidates = get_sorted_candidates()
                if candidates:
                    move = candidates[0]
                    undo = apply_move(move)
                    move_sequence.append(move['type'])
                    move_path.append(dict(move))
                    total_steps[0] += 1
                    nodes_explored[0] += 1
                    stack.append({'candidates': candidates, 'index': 0, 'undo': undo, 'move': move})
                    continue
                else:
                    # Dead end, fall through to backtrack
                    pass
            else:
                # At max depth: greedy playout
                won, playout_undos, playout_types, playout_dicts = greedy_playout()
                if won:
                    move_sequence.extend(playout_types)
                    move_path.extend(playout_dicts)
                    result = _build_result(move_sequence, move_path)
                    # Undo playout
                    for u in reversed(playout_undos):
                        undo_move(u)
                    # Undo stack
                    for node in reversed(stack):
                        undo_move(node['undo'])
                    # Undo greedy phase
                    for u in reversed(greedy_undos):
                        undo_move(u)
                    move_sequence.clear()
                    move_path.clear()
                    return result
                else:
                    # Undo playout
                    for u in reversed(playout_undos):
                        undo_move(u)
                    # Fall through to backtrack

            # Backtrack: try next candidate at current level, or pop and try parent's next
            while stack:
                node = stack[-1]
                next_idx = node['index'] + 1
                if next_idx < len(node['candidates']):
                    # Undo current move
                    undo_move(node['undo'])
                    move_sequence.pop()
                    move_path.pop()
                    # Try next candidate
                    node['index'] = next_idx
                    move = node['candidates'][next_idx]
                    undo = apply_move(move)
                    move_sequence.append(move['type'])
                    move_path.append(dict(move))
                    total_steps[0] += 1
                    nodes_explored[0] += 1
                    node['undo'] = undo
                    node['move'] = move
                    break
                else:
                    # Exhausted candidates at this level, pop
                    undo_move(node['undo'])
                    move_sequence.pop()
                    move_path.pop()
                    stack.pop()

        # Clean up any remaining stack
        for node in reversed(stack):
            undo_move(node['undo'])
        # Undo greedy phase
        for u in reversed(greedy_undos):
            undo_move(u)

        return None  # Failed

    # ── Multi-round strategy ──

    # Priority Strategy (up to MAX_SOLVER_ROUNDS rounds)
    for _ in range(MAX_SOLVER_ROUNDS):
        result = solve_with_backtracking(use_priority=True)
        if result and result['won']:
            result['strategyType'] = 'priority'
            return result

    # Equality Strategy (up to MAX_SOLVER_ROUNDS rounds)
    for _ in range(MAX_SOLVER_ROUNDS):
        result = solve_with_backtracking(use_priority=False)
        if result and result['won']:
            result['strategyType'] = 'equality'
            return result

    return {
        'won': False,
        'stepsUsed': -1,
        'moveStats': empty_move_stats(),
        'strategyType': 'none',
        'nodesExplored': nodes_explored[0],
    }


# ── MCTS Solver (Monte Carlo Tree Search) — preserved for future use ────

MAX_NODES = 2000000
DEFAULT_MCTS_ITERATIONS = 5000


def can_stack_on_column(card, col):
    """Check if a card can be stacked on a column."""
    if len(col) == 0:
        return True
    top_card = col[-1]
    if top_card['card']['type'] == 'gold':
        return False  # sealed column
    return card['category'] == top_card['card']['category']


def verify_solvable(tableau, category_targets, max_steps, max_slots, hand_pile, mcts_iterations=None):
    """MCTS solver to verify a level layout is solvable.

    NOTE: Preserved for future use. Currently not called — replaced by solve_level().

    Returns: { solvable: bool, nodesExplored: int, stepsUsed: int, moveStats: dict }
    """
    if mcts_iterations is None:
        mcts_iterations = DEFAULT_MCTS_ITERATIONS

    # Deep clone state
    state = {
        'tableau': [[{'card': dict(tc['card']), 'faceUp': tc['faceUp']} for tc in col] for col in tableau],
        'slots': [None] * max_slots,
        'stepsLeft': max_steps,
        'completedCount': 0,
        'numCategories': len(category_targets),
        'handPile': [dict(c) for c in hand_pile],
        'handDisplay': [],
        'recycleCount': 0,
    }

    nodes_explored = [0]  # mutable counter
    best_move_types = [None]  # track best solution's move type sequence

    def get_top_card(col):
        return col[-1] if col else None

    def get_moves():
        moves = []
        has_empty_slot = any(s is None for s in state['slots'])

        # Tableau top cards → slot (single and multi-card)
        for ci in range(len(state['tableau'])):
            col = state['tableau'][ci]
            top = get_top_card(col)
            if not top or not top['faceUp']:
                continue

            # Check multi-card drag first
            top_idx = len(col) - 1
            cat = col[top_idx]['card']['category']
            start_idx = top_idx
            while start_idx > 0 and col[start_idx - 1]['faceUp'] and col[start_idx - 1]['card']['category'] == cat:
                start_idx -= 1
            drag_count = top_idx - start_idx + 1

            added_multi = False
            if drag_count >= 2:
                # Case A: gold on top + regulars below
                if col[top_idx]['card']['type'] == 'gold' and has_empty_slot:
                    all_regular_below = all(col[i]['card']['type'] == 'regular' for i in range(start_idx, top_idx))
                    if all_regular_below:
                        moves.append({'type': 'tableau_multi_to_slot', 'colIdx': ci, 'startIdx': start_idx, 'count': drag_count})
                        added_multi = True

                # Case B: all regular → match existing slot
                if not added_multi and all(col[i]['card']['type'] == 'regular' for i in range(start_idx, top_idx + 1)):
                    for si, s in enumerate(state['slots']):
                        if s is not None and s['key'] == cat and s['collected'] + drag_count <= s['target']:
                            moves.append({'type': 'tableau_multi_to_slot', 'colIdx': ci, 'startIdx': start_idx, 'count': drag_count})
                            added_multi = True
                            break

            # Single card moves (always available alongside multi, except when multi covers)
            if top['card']['type'] == 'regular' and not added_multi:
                slot_idx = None
                for si, s in enumerate(state['slots']):
                    if s is not None and s['key'] == top['card']['category'] and s['collected'] < s['target']:
                        slot_idx = si
                        break
                if slot_idx is not None:
                    moves.append({'type': 'tableau_to_slot', 'colIdx': ci, 'slotIdx': slot_idx})

            if top['card']['type'] == 'gold' and has_empty_slot and not added_multi:
                moves.append({'type': 'tableau_gold_to_slot', 'colIdx': ci})

        # Hand display → slot
        if state['handDisplay']:
            top_card = state['handDisplay'][-1]
            if top_card['type'] == 'regular':
                slot_idx = None
                for si, s in enumerate(state['slots']):
                    if s is not None and s['key'] == top_card['category'] and s['collected'] < s['target']:
                        slot_idx = si
                        break
                if slot_idx is not None:
                    moves.append({'type': 'display_to_slot', 'slotIdx': slot_idx})

            if top_card['type'] == 'gold' and has_empty_slot:
                moves.append({'type': 'display_gold_to_slot'})

        # Tableau → column (single card)
        for ci in range(len(state['tableau'])):
            col = state['tableau'][ci]
            top = get_top_card(col)
            if not top or not top['faceUp']:
                continue
            for ti in range(len(state['tableau'])):
                if ti == ci:
                    continue
                if can_stack_on_column(top['card'], state['tableau'][ti]):
                    moves.append({'type': 'tableau_to_column', 'srcCol': ci, 'dstCol': ti})

        # Tableau → column (multi-card: consecutive same-category face-up cards ≥2)
        for ci in range(len(state['tableau'])):
            col = state['tableau'][ci]
            if not col:
                continue
            top_idx = len(col) - 1
            if not col[top_idx]['faceUp']:
                continue
            cat = col[top_idx]['card']['category']
            start_idx = top_idx
            while start_idx > 0 and col[start_idx - 1]['faceUp'] and col[start_idx - 1]['card']['category'] == cat:
                start_idx -= 1
            drag_count = top_idx - start_idx + 1
            if drag_count < 2:
                continue
            bottom_card = col[start_idx]['card']
            for ti in range(len(state['tableau'])):
                if ti == ci:
                    continue
                if can_stack_on_column(bottom_card, state['tableau'][ti]):
                    moves.append({'type': 'tableau_multi_to_column', 'srcCol': ci, 'dstCol': ti, 'startIdx': start_idx, 'count': drag_count})

        # Hand display → column
        if state['handDisplay']:
            top_card = state['handDisplay'][-1]
            for ti in range(len(state['tableau'])):
                if can_stack_on_column(top_card, state['tableau'][ti]):
                    moves.append({'type': 'display_to_column', 'dstCol': ti})

        # Flip hand
        if state['handPile']:
            moves.append({'type': 'flip_hand'})

        # Recycle
        if not state['handPile'] and state['handDisplay'] and state['recycleCount'] < MAX_RECYCLES:
            moves.append({'type': 'recycle'})

        return moves

    def auto_flip(col):
        if col and not col[-1]['faceUp']:
            col[-1]['faceUp'] = True
            return True
        return False

    def apply_move(move):
        undo = {'type': move['type']}

        if move['type'] == 'tableau_multi_to_slot':
            state['stepsLeft'] -= 1
            col = state['tableau'][move['colIdx']]
            start_idx = move['startIdx']
            removed = col[start_idx:]
            del col[start_idx:]
            undo['colIdx'] = move['colIdx']
            undo['removed'] = removed
            undo['startIdx'] = start_idx

            top_card = removed[-1]
            if top_card['card']['type'] == 'gold':
                # Case A: gold opens slot + collect regulars
                empty_idx = next(i for i, s in enumerate(state['slots']) if s is None)
                regular_count = len(removed) - 1
                target = category_targets.get(top_card['card']['category'], 0)
                state['slots'][empty_idx] = {
                    'key': top_card['card']['category'],
                    'collected': regular_count,
                    'target': target,
                }
                undo['slotIdx'] = empty_idx
                undo['slotWasNone'] = True
                if regular_count >= target:
                    undo['completed'] = dict(state['slots'][empty_idx])
                    state['slots'][empty_idx] = None
                    state['completedCount'] += 1
            else:
                # Case B: all regular → add to existing slot
                cat = removed[0]['card']['category']
                for si, s in enumerate(state['slots']):
                    if s is not None and s['key'] == cat:
                        undo['slotIdx'] = si
                        undo['slotWasNone'] = False
                        undo['prevCollected'] = s['collected']
                        s['collected'] += len(removed)
                        if s['collected'] >= s['target']:
                            undo['completed'] = dict(s)
                            state['slots'][si] = None
                            state['completedCount'] += 1
                        break
            undo['flipped'] = auto_flip(col)

        elif move['type'] == 'tableau_to_slot':
            state['stepsLeft'] -= 1
            col = state['tableau'][move['colIdx']]
            tc = col.pop()
            undo['colIdx'] = move['colIdx']
            undo['tc'] = tc
            undo['slotIdx'] = move['slotIdx']

            slot = state['slots'][move['slotIdx']]
            undo['prevCollected'] = slot['collected']
            slot['collected'] += 1
            if slot['collected'] >= slot['target']:
                undo['completed'] = dict(slot)
                state['slots'][move['slotIdx']] = None
                state['completedCount'] += 1
            undo['flipped'] = auto_flip(col)

        elif move['type'] == 'tableau_gold_to_slot':
            state['stepsLeft'] -= 1
            col = state['tableau'][move['colIdx']]
            tc = col.pop()
            undo['colIdx'] = move['colIdx']
            undo['tc'] = tc

            empty_idx = next(i for i, s in enumerate(state['slots']) if s is None)
            state['slots'][empty_idx] = {
                'key': tc['card']['category'],
                'collected': 0,
                'target': category_targets.get(tc['card']['category'], 0),
            }
            undo['slotIdx'] = empty_idx
            undo['flipped'] = auto_flip(col)

        elif move['type'] == 'display_to_slot':
            state['stepsLeft'] -= 1
            card = state['handDisplay'].pop()
            undo['card'] = card
            undo['slotIdx'] = move['slotIdx']

            slot = state['slots'][move['slotIdx']]
            undo['prevCollected'] = slot['collected']
            slot['collected'] += 1
            if slot['collected'] >= slot['target']:
                undo['completed'] = dict(slot)
                state['slots'][move['slotIdx']] = None
                state['completedCount'] += 1

        elif move['type'] == 'display_gold_to_slot':
            state['stepsLeft'] -= 1
            card = state['handDisplay'].pop()
            undo['card'] = card
            empty_idx = next(i for i, s in enumerate(state['slots']) if s is None)
            state['slots'][empty_idx] = {
                'key': card['category'],
                'collected': 0,
                'target': category_targets.get(card['category'], 0),
            }
            undo['slotIdx'] = empty_idx

        elif move['type'] == 'tableau_to_column':
            state['stepsLeft'] -= 1
            src_col = state['tableau'][move['srcCol']]
            tc = src_col.pop()
            undo['srcCol'] = move['srcCol']
            undo['dstCol'] = move['dstCol']
            undo['tc'] = tc
            state['tableau'][move['dstCol']].append(tc)
            undo['flipped'] = auto_flip(src_col)

        elif move['type'] == 'tableau_multi_to_column':
            state['stepsLeft'] -= 1
            src_col = state['tableau'][move['srcCol']]
            start_idx = move['startIdx']
            removed = src_col[start_idx:]
            del src_col[start_idx:]
            undo['srcCol'] = move['srcCol']
            undo['dstCol'] = move['dstCol']
            undo['removed'] = removed
            undo['startIdx'] = start_idx
            state['tableau'][move['dstCol']].extend(removed)
            undo['flipped'] = auto_flip(src_col)

        elif move['type'] == 'display_to_column':
            state['stepsLeft'] -= 1
            card = state['handDisplay'].pop()
            undo['card'] = card
            undo['dstCol'] = move['dstCol']
            state['tableau'][move['dstCol']].append({'card': card, 'faceUp': True})

        elif move['type'] == 'flip_hand':
            state['stepsLeft'] -= 1
            card = state['handPile'].pop()
            state['handDisplay'].append(card)
            undo['card'] = card

        elif move['type'] == 'recycle':
            state['stepsLeft'] -= 1
            undo['displaySnapshot'] = list(state['handDisplay'])
            state['handPile'] = list(reversed(state['handDisplay']))
            state['handDisplay'] = []
            state['recycleCount'] += 1

        return undo

    def undo_move(undo):
        if undo['type'] == 'tableau_multi_to_slot':
            state['stepsLeft'] += 1
            col = state['tableau'][undo['colIdx']]
            if undo.get('flipped'):
                col[-1]['faceUp'] = False
            # Restore removed cards
            col.extend(undo['removed'])
            # Restore slot
            if 'completed' in undo:
                state['completedCount'] -= 1
            if undo['slotWasNone']:
                # Was gold case: slot was created, remove it
                si = undo['slotIdx']
                if state['slots'][si] is None and 'completed' in undo:
                    pass  # already None from completion
                state['slots'][si] = None
            else:
                # Was regular case: restore previous collected count
                si = undo['slotIdx']
                if state['slots'][si] is None and 'completed' in undo:
                    state['slots'][si] = undo['completed']
                state['slots'][si]['collected'] = undo['prevCollected']

        elif undo['type'] == 'tableau_to_slot':
            state['stepsLeft'] += 1
            col = state['tableau'][undo['colIdx']]
            if undo.get('flipped'):
                col[-1]['faceUp'] = False
            col.append(undo['tc'])
            if 'completed' in undo:
                state['completedCount'] -= 1
                state['slots'][undo['slotIdx']] = undo['completed']
                state['slots'][undo['slotIdx']]['collected'] = undo['prevCollected']
            else:
                state['slots'][undo['slotIdx']]['collected'] -= 1

        elif undo['type'] == 'tableau_gold_to_slot':
            state['stepsLeft'] += 1
            col = state['tableau'][undo['colIdx']]
            if undo.get('flipped'):
                col[-1]['faceUp'] = False
            col.append(undo['tc'])
            state['slots'][undo['slotIdx']] = None

        elif undo['type'] == 'display_to_slot':
            state['stepsLeft'] += 1
            if 'completed' in undo:
                state['completedCount'] -= 1
                state['slots'][undo['slotIdx']] = undo['completed']
                state['slots'][undo['slotIdx']]['collected'] = undo['prevCollected']
            else:
                state['slots'][undo['slotIdx']]['collected'] -= 1
            state['handDisplay'].append(undo['card'])

        elif undo['type'] == 'display_gold_to_slot':
            state['stepsLeft'] += 1
            state['slots'][undo['slotIdx']] = None
            state['handDisplay'].append(undo['card'])

        elif undo['type'] == 'tableau_to_column':
            state['stepsLeft'] += 1
            state['tableau'][undo['dstCol']].pop()
            if undo.get('flipped'):
                state['tableau'][undo['srcCol']][-1]['faceUp'] = False
            state['tableau'][undo['srcCol']].append(undo['tc'])

        elif undo['type'] == 'tableau_multi_to_column':
            state['stepsLeft'] += 1
            dst_col = state['tableau'][undo['dstCol']]
            count = len(undo['removed'])
            del dst_col[-count:]
            if undo.get('flipped'):
                state['tableau'][undo['srcCol']][-1]['faceUp'] = False
            state['tableau'][undo['srcCol']].extend(undo['removed'])

        elif undo['type'] == 'display_to_column':
            state['stepsLeft'] += 1
            state['tableau'][undo['dstCol']].pop()
            state['handDisplay'].append(undo['card'])

        elif undo['type'] == 'flip_hand':
            state['stepsLeft'] += 1
            state['handDisplay'].pop()
            state['handPile'].append(undo['card'])

        elif undo['type'] == 'recycle':
            state['stepsLeft'] += 1
            state['handDisplay'] = undo['displaySnapshot']
            state['handPile'] = []
            state['recycleCount'] -= 1

    # ── MCTS Implementation ──────────────────────────────────────────

    import math

    EXPLORATION_C = 1.414
    best_steps = [None]

    class MCTSNode:
        __slots__ = ['parent', 'move', 'children', 'untried_moves', 'visits', 'wins', 'total_steps', 'depth']
        def __init__(self, parent, move, depth):
            self.parent = parent
            self.move = move
            self.children = []
            self.untried_moves = None  # lazy init
            self.visits = 0
            self.wins = 0
            self.total_steps = 0
            self.depth = depth

        def ucb1(self, parent_visits):
            if self.visits == 0:
                return float('inf')
            exploit = self.wins / self.visits
            explore = EXPLORATION_C * math.sqrt(math.log(parent_visits) / self.visits)
            return exploit + explore

        def best_child(self):
            pv = self.visits
            best = None
            best_val = -1
            for c in self.children:
                v = c.ucb1(pv)
                if v > best_val:
                    best_val = v
                    best = c
            return best

    def init_untried_moves(node):
        if node.untried_moves is None:
            node.untried_moves = get_moves()
            random.shuffle(node.untried_moves)

    def get_move_weight(move):
        """Higher weight = higher priority for greedy rollout."""
        mt = move['type']
        if mt == 'tableau_multi_to_slot':
            return 150
        if mt in ('tableau_to_slot', 'tableau_gold_to_slot', 'display_to_slot', 'display_gold_to_slot'):
            return 100
        if mt in ('tableau_to_column', 'tableau_multi_to_column'):
            # Prefer moves that uncover hidden cards
            return 50
        if mt == 'display_to_column':
            return 20
        if mt == 'flip_hand':
            return 20
        return 10  # recycle

    def greedy_rollout_choice(moves):
        """Greedy: pick the highest-weight move, random tiebreak among same weight."""
        best_weight = -1
        candidates = []
        for m in moves:
            w = get_move_weight(m)
            if w > best_weight:
                best_weight = w
                candidates = [m]
            elif w == best_weight:
                candidates.append(m)
        if len(candidates) == 1:
            return candidates[0]
        return candidates[random.randint(0, len(candidates) - 1)]

    def rollout():
        rollout_undos = []
        rollout_move_types = []
        won = False
        while state['stepsLeft'] > 0:
            if state['completedCount'] >= state['numCategories']:
                won = True
                break
            moves = get_moves()
            if not moves:
                break
            move = greedy_rollout_choice(moves)
            rollout_undos.append(apply_move(move))
            rollout_move_types.append(move['type'])
            nodes_explored[0] += 1
        steps_used = max_steps - state['stepsLeft']
        for u in reversed(rollout_undos):
            undo_move(u)
        return won, steps_used, rollout_move_types

    def mcts_iterate(root):
        # SELECT
        node = root
        path_undos = []
        path_move_types = []
        while node.untried_moves is not None and len(node.untried_moves) == 0 and node.children:
            node = node.best_child()
            path_undos.append(apply_move(node.move))
            path_move_types.append(node.move['type'])
            nodes_explored[0] += 1

        # Check if already won at this node
        if state['completedCount'] >= state['numCategories']:
            steps_used = max_steps - state['stepsLeft']
            if best_steps[0] is None or steps_used < best_steps[0]:
                best_steps[0] = steps_used
                best_move_types[0] = list(path_move_types)
            n = node
            while n is not None:
                n.visits += 1
                n.wins += 1
                n.total_steps += steps_used
                n = n.parent
            for u in reversed(path_undos):
                undo_move(u)
            return

        # EXPAND
        init_untried_moves(node)
        if node.untried_moves:
            move = node.untried_moves.pop()
            child = MCTSNode(parent=node, move=move, depth=node.depth + 1)
            node.children.append(child)
            path_undos.append(apply_move(move))
            path_move_types.append(move['type'])
            nodes_explored[0] += 1
            node = child

        # SIMULATE
        won, steps_used, rollout_move_types = rollout()
        if won and (best_steps[0] is None or steps_used < best_steps[0]):
            best_steps[0] = steps_used
            best_move_types[0] = path_move_types + rollout_move_types

        # BACKPROPAGATE
        n = node
        while n is not None:
            n.visits += 1
            if won:
                n.wins += 1
                n.total_steps += steps_used
            n = n.parent

        # Undo path
        for u in reversed(path_undos):
            undo_move(u)

    root = MCTSNode(parent=None, move=None, depth=0)
    init_untried_moves(root)

    for _ in range(mcts_iterations):
        mcts_iterate(root)
        if nodes_explored[0] > MAX_NODES:
            break

    solvable = best_steps[0] is not None
    steps_used = best_steps[0] if solvable else 0

    # Build moveStats from best solution's move type sequence
    mcts_move_stats = empty_move_stats()
    if solvable and best_move_types[0]:
        for mt in best_move_types[0]:
            cat = classify_move(mt)
            if cat:
                mcts_move_stats[cat] += 1

    return {'solvable': solvable, 'nodesExplored': nodes_explored[0], 'stepsUsed': steps_used, 'moveStats': mcts_move_stats}


